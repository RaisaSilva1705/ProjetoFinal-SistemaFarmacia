                <ol>
                    <li>Foque o cursor no campo <strong>Código de Barras (F2)</strong>.</li>
                    <li>Use o leitor de código de barras para adicionar produtos. A quantidade padrão é 1.</li>
                    <li>Para vender mais de uma unidade, altere o campo <strong>Quantidade</strong> antes de escanear.</li>
