                <p>Use estas teclas para acelerar sua operação:</p>
                <ul class="list-group">
                    <li class="list-group-item"><strong>F1:</strong> Abre esta janela de ajuda.</li>
                    <li class="list-group-item"><strong>F2:</strong> Foca no campo "Código de Barras" para iniciar uma venda.</li>
                    <li class="list-group-item"><strong>F3:</strong> Abre a janela de "Consulta Rápida de Preço".</li>
                    <li class="list-group-item"><strong>F4:</strong> Foca no campo "CPF/CNPJ do Cliente" para identificar o cliente.</li>
                    <li class="list-group-item"><strong>F8:</strong> Cancela a venda atual.</li>
                    <li class="list-group-item"><strong>F9:</strong> Abre o menu de "Funcionalidades Extras" (Sangria, Devolução).</li>
                    <li class="list-group-item"><strong>F10:</strong> Inicia o processo de fechamento do caixa.</li>
                    <li class="list-group-item"><strong>Teclas de 1 a 4:</strong> Abrem o modal de pagamento para Dinheiro, Crédito, Débito e PIX, respectivamente.</li>
                </ul>
