                <ul>
                    <li><strong>Carregar Pré-Venda:</strong> Digite ou escaneie o código da pré-venda (iniciado com '99') no campo "Código de Barras".</li>
                    <li><strong>Verificar Itens de Controlados:</strong> Para liberar um item de uma pré-venda de controlados, escaneie o código de barras do produto físico. O sistema fará a validação automática.</li>
